export function translate(locale: Locale, key: string, vars: Record<string, unknown> = {}): string {
  const pair = extra[key] || pairs[key];
  let value = pair ? pair[locale === 'en-US' ? 1 : 0] : (locale === 'en-US' ? en : zh)[key as keyof typeof zh] || key;
  for (const [k, v] of Object.entries(vars)) value = value.split(`{${k}}`).join(String(v));
  return value;
}
